-- AI Trainer Playground history.
--
-- Until now a Playground conversation lived only in the browser and was lost
-- on refresh. These two tables keep every Playground conversation and turn so
-- a tester can reopen one, see exactly which message produced which reply,
-- and continue it from its saved state.
--
-- Kept apart from WhatsApp on purpose: real chats live in wa_messages and the
-- live trainer path in ai_turns / ai_conversation_state. Nothing here is ever
-- read by a bot or shown in Conversations.
--
-- Same access rule as every ai_ table (migration 0037): RLS on, no policy, no
-- anon/authenticated grant. Only the ai-trainer Edge Function reads and
-- writes them, with the service role, after its Management check.
--
-- client_turn_id is generated by the browser per send and is unique per
-- conversation, so a retried request returns the saved turn instead of
-- running the model again and storing a duplicate.
--
-- Additive and safe to run multiple times. Run in: Supabase Dashboard → SQL Editor.

create table if not exists ai_playground_conversations (
  id uuid primary key default gen_random_uuid(),
  bot text not null check (bot in ('eyad','dubai')),
  source text not null check (source in ('drafts','snapshot')),
  snapshot_id uuid references ai_snapshots(id),
  setup jsonb not null default '{}' check (jsonb_typeof(setup) = 'object'),
  state jsonb,
  title text not null default '',
  turn_count int not null default 0,
  created_by_claimed text not null,
  created_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  check ((source = 'drafts' and snapshot_id is null) or (source = 'snapshot' and snapshot_id is not null))
);
create index if not exists ai_playground_conversations_recent on ai_playground_conversations (last_activity_at desc);

create table if not exists ai_playground_turns (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references ai_playground_conversations(id) on delete cascade,
  seq int not null check (seq >= 1),
  client_turn_id text not null check (length(client_turn_id) between 8 and 64),
  customer_text text not null,
  setup jsonb not null default '{}',
  returning_contact boolean not null default false,
  state_before jsonb,
  state_after jsonb,
  reply text,
  media jsonb not null default '[]',
  handoff boolean not null default false,
  outcome text not null,
  trace jsonb,
  error text,
  checksum text,
  core_version text,
  created_at timestamptz not null default now(),
  finished_at timestamptz,
  unique (conversation_id, seq),
  unique (conversation_id, client_turn_id)
);

do $$ declare t text; begin
  foreach t in array array['ai_playground_conversations','ai_playground_turns'] loop
    execute format('alter table %I enable row level security', t);
    execute format('revoke all on %I from anon, authenticated', t);
  end loop;
end $$;

