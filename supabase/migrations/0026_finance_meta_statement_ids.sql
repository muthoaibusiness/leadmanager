-- 0026 · Finance: Meta statement IDs, each issued once, never reused.
--
-- A Meta statement carries a Transaction ID (layout.vendorRef) and a Reference
-- ID (layout.paymentRef). The finance function issues both when the statement
-- is first saved as Meta and records them here. The primary key is
-- '<kind>:<value>', so a value can be issued to one statement only, across all
-- companies. Rows are never updated or deleted (the 0024 append-only trigger),
-- so a deleted draft's IDs stay taken. From the first save on, the function
-- takes a statement's IDs from this table, whatever the editor sends.
--
-- Also here: every ID already on a Meta statement is recorded (oldest statement
-- first), and each Meta draft that got IDs this way gets layout.issuedIds (the
-- IDs issued to it), which the editor locks those fields on. Final statements
-- keep their layout untouched. Other statement categories are not touched.
--
-- Needs 0024 (finance_history_append_only). Safe to run more than once.
-- Apply in the Supabase SQL editor BEFORE deploying the finance function that
-- issues IDs (without this table that function refuses to save Meta statements).
--
-- Rollback (loses which IDs were issued; run only together with redeploying the
-- previous finance function):
--   begin;
--   update public.finance_invoices set layout = layout - 'issuedIds' where layout ? 'issuedIds';
--   drop table public.finance_statement_ids;
--   commit;

begin;

create table if not exists public.finance_statement_ids (
  id              text primary key,             -- '<kind>:<value>': a value is issued once, ever
  kind            text not null check (kind in ('transaction', 'reference')),
  value           text not null,
  company_id      text not null,
  invoice_id      text not null,                -- no foreign key: the row outlives a deleted draft
  invoice_number  text,
  source          text not null check (source in ('generated', 'receipt')), -- generated by WEPRO, or copied from the vendor's receipt
  issued_by       text,
  issued_at       timestamptz not null default now()
);
create index if not exists finance_statement_ids_invoice_idx on public.finance_statement_ids (invoice_id);

-- Like every finance_* table: RLS on, no policy. Only the finance function
-- (service role) reads or writes it.
alter table public.finance_statement_ids enable row level security;

drop trigger if exists finance_statement_ids_append_only on public.finance_statement_ids;
create trigger finance_statement_ids_append_only before update or delete on public.finance_statement_ids
  for each row execute function public.finance_history_append_only();
drop trigger if exists finance_statement_ids_no_truncate on public.finance_statement_ids;
create trigger finance_statement_ids_no_truncate before truncate on public.finance_statement_ids
  for each statement execute function public.finance_history_append_only();

-- The IDs already on Meta statements. When two statements share a value, the
-- older one keeps it (see the notice below).
insert into public.finance_statement_ids (id, kind, value, company_id, invoice_id, invoice_number, source, issued_by, issued_at)
select k.kind || ':' || k.value, k.kind, k.value, i.company_id, i.id, i.number,
       case when k.gen then 'generated' else 'receipt' end, i.created_by, i.created_at
from public.finance_invoices i
cross join lateral (values
  ('transaction', nullif(btrim(i.layout->>'vendorRef'), ''), i.layout->>'vendorRefGen' = 'true'),
  ('reference',   nullif(btrim(i.layout->>'paymentRef'), ''), i.layout->>'paymentRefGen' = 'true')
) as k(kind, value, gen)
where i.layout->>'template' = 'meta' and k.value is not null
order by i.created_at, i.id
on conflict (id) do nothing;

update public.finance_invoices i
set layout = i.layout || jsonb_build_object('issuedIds', ids.obj)
from (
  select invoice_id, jsonb_object_agg(k, v) as obj
  from (
    select invoice_id, case kind when 'transaction' then 'vendorRef' else 'paymentRef' end as k, to_jsonb(value) as v from public.finance_statement_ids
    union all
    select invoice_id, case kind when 'transaction' then 'vendorRefGen' else 'paymentRefGen' end, to_jsonb(source = 'generated') from public.finance_statement_ids
  ) kv
  group by invoice_id
) ids
where ids.invoice_id = i.id and i.status = 'DRAFT' and i.layout->>'template' = 'meta' and not (i.layout ? 'issuedIds');

do $$
declare n integer;
begin
  select count(*) into n
  from public.finance_invoices i
  cross join lateral (values ('transaction', nullif(btrim(i.layout->>'vendorRef'), '')), ('reference', nullif(btrim(i.layout->>'paymentRef'), ''))) as k(kind, value)
  where i.layout->>'template' = 'meta' and k.value is not null
    and not exists (select 1 from public.finance_statement_ids s where s.id = k.kind || ':' || k.value and s.invoice_id = i.id);
  if n > 0 then
    raise notice '0026: % ID(s) on Meta statements are also on an older statement and were not recorded for the newer one. List them with: select i.number, i.layout->>''vendorRef'', i.layout->>''paymentRef'' from finance_invoices i where i.layout->>''template'' = ''meta'' order by i.created_at;', n;
  end if;
end $$;

commit;
